// The part of the in-browser analyzer shared by every source of files: a
// local folder (localAnalyzer.js, the File System Access API) and a GitHub
// repository (githubAnalyzer.js, the GitHub REST API). Both end up with the
// same thing, a Map of absolute-style path ("/src/app.ts") -> text, and hand
// it here to become a declaration graph document — the same shape
// analyzers/ts/analyze.mjs's analyze() produces, walked by the very same
// analyzers/ts/core.mjs (copied into vendor/analyzer-core.js by `npm run
// vendor` since the published site only ever serves site/).
//
// The `ts` compiler itself (site/vendor/typescript.js, ~9MB) is loaded lazily
// on first use, as a classic <script> tag rather than a static import: every
// other page load — the overwhelming majority, just viewing a dataset — must
// not pay for fetching it. vendor/analyzer-core.js is imported lazily too, for
// a different reason: it is generated by `npm run vendor` and gitignored
// (analyzers/ts/core.mjs is the source of truth), so a static import of it
// here would break loading this module anywhere that hasn't run that build
// step yet — including node:test, which never opens a browser at all.

let tsPromise = null;
/** Load vendor/typescript.js once, returning the `ts` global it defines. */
export function loadTypeScript() {
  if (window.ts) return Promise.resolve(window.ts);
  tsPromise ??= new Promise((resolve, reject) => {
    const script = document.createElement("script");
    script.src = "vendor/typescript.js";
    script.onload = () => resolve(window.ts);
    script.onerror = () => reject(new Error("could not load vendor/typescript.js — run `npm run vendor` (see README.md)"));
    document.head.append(script);
  });
  return tsPromise;
}

function compilerOptions(ts) {
  return {
    allowJs: true,
    checkJs: false,
    noEmit: true,
    noResolve: false,
    skipLibCheck: true,
    target: ts.ScriptTarget.ESNext,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    jsx: ts.JsxEmit.Preserve,
    allowSyntheticDefaultImports: true,
    esModuleInterop: true,
  };
}

const libCache = new Map();
async function readLib(fileName) {
  if (!libCache.has(fileName)) {
    const res = await fetch(`vendor/ts-lib/${fileName}`);
    libCache.set(fileName, res.ok ? await res.text() : undefined);
  }
  return libCache.get(fileName);
}

/** Every lib.*.d.ts the default lib file references, transitively (mirrors scripts/vendor.mjs's own closure walk). */
async function loadLibClosure(ts, options) {
  const libFiles = new Map();
  const queue = [ts.getDefaultLibFileName(options)];
  while (queue.length) {
    const fileName = queue.shift();
    if (libFiles.has(fileName)) continue;
    const text = await readLib(fileName);
    libFiles.set(fileName, text);
    if (text === undefined) continue;
    for (const m of text.matchAll(/\/\/\/\s*<reference\s+lib="([^"]+)"/g)) queue.push(`lib.${m[1]}.d.ts`);
  }
  return libFiles;
}

/** A ts.CompilerHost reading from an in-memory file map plus the vendored lib.*.d.ts files. */
function createHost(ts, files, libFiles) {
  const sourceFiles = new Map();
  const read = (fileName) => files.get(fileName) ?? libFiles.get(fileName);
  return {
    getSourceFile(fileName, languageVersionOrOptions) {
      if (!sourceFiles.has(fileName)) {
        const text = read(fileName);
        sourceFiles.set(fileName, text === undefined ? undefined : ts.createSourceFile(fileName, text, languageVersionOrOptions, true));
      }
      return sourceFiles.get(fileName);
    },
    getDefaultLibFileName: (options) => ts.getDefaultLibFileName(options),
    writeFile: () => {},
    getCurrentDirectory: () => "/",
    getCanonicalFileName: (f) => f,
    useCaseSensitiveFileNames: () => true,
    getNewLine: () => "\n",
    fileExists: (f) => read(f) !== undefined,
    readFile: (f) => read(f),
    directoryExists: () => true,
    getDirectories: () => [],
  };
}

/**
 * Analyze `files` (Map of absolute-style path, e.g. "/src/app.ts", -> text).
 * @param {object} opts { name, nested, rootLabel }
 * @returns the same document shape analyzers/ts/analyze.mjs's analyze() returns
 */
export async function analyzeFiles(files, { name, nested, rootLabel } = {}) {
  if (files.size === 0) throw new Error("no .js/.ts source files found (node_modules, .git, dist, build, coverage and vendor are skipped)");
  const ts = await loadTypeScript();
  const options = compilerOptions(ts);
  const libFiles = await loadLibClosure(ts, options);
  const host = createHost(ts, files, libFiles);
  const fileNames = [...files.keys()];
  const program = ts.createProgram({ rootNames: fileNames, options, host });
  const { createCore } = await import("../vendor/analyzer-core.js");
  const { analyzeProgram } = createCore(ts);
  return analyzeProgram({
    program,
    files: fileNames,
    stripPrefix: "/",
    rootLabel: rootLabel ?? name ?? ".",
    options: { name, nested, language: "javascript" },
  });
}
